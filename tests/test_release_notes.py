"""The self-update page's release notes: bundled, changelog fallback, no invention."""

from __future__ import annotations

import json

from perun import release_notes

SAMPLE = """# Perun - Changelog

Intro text that is not part of any release.

## Unreleased

_No unreleased changes yet._

## v0.10.43

*Released 2026-11-01.*

### The control project

* Something changed.

## v0.10.42

*Released 2026-10-31.*

* An older change.
"""


def test_parse_changelog_returns_final_releases_newest_first():
    releases = release_notes.parse_changelog(SAMPLE)

    assert [r["version"] for r in releases] == ["0.10.43", "0.10.42"]
    assert releases[0]["date"] == "2026-11-01"
    assert "Something changed" in releases[0]["body"]
    assert releases[1]["body"].strip() == "* An older change."


def test_unreleased_and_prose_are_not_releases():
    releases = release_notes.parse_changelog(SAMPLE)
    assert len(releases) == 2
    assert all(r["version"] for r in releases)


def test_bundled_notes_win_over_the_changelog(tmp_path, monkeypatch):
    bundled = tmp_path / "release_notes.json"
    bundled.write_text(json.dumps({"releases": [
        {"version": "0.10.43", "date": "2026-11-01", "body": "bundled body"}]}),
        encoding="utf-8")
    monkeypatch.setattr(release_notes, "BUNDLED_PATH", bundled)
    monkeypatch.setattr(release_notes, "__version__", "0.10.43")

    notes = release_notes.for_version()

    assert notes["source"] == "bundled"
    assert notes["body"] == "bundled body"
    assert notes["installed"] is True


def test_a_checkout_falls_back_to_the_changelog(tmp_path, monkeypatch):
    monkeypatch.setattr(release_notes, "BUNDLED_PATH", tmp_path / "missing.json")
    changelog = tmp_path / "CHANGELOG.md"
    changelog.write_text(SAMPLE, encoding="utf-8")
    monkeypatch.setattr(release_notes, "changelog_paths", lambda: [changelog])

    notes = release_notes.for_version("0.10.42")

    assert notes["source"] == "changelog"
    assert "older change" in notes["body"]
    assert notes["installed"] is False


def test_an_unknown_version_is_unavailable_not_invented(tmp_path, monkeypatch):
    monkeypatch.setattr(release_notes, "BUNDLED_PATH", tmp_path / "missing.json")
    monkeypatch.setattr(release_notes, "changelog_paths", lambda: [tmp_path / "nope.md"])

    notes = release_notes.for_version("9.9.9")

    assert notes["source"] == "unavailable"
    assert notes["body"] == ""


def test_the_package_ships_notes_for_the_running_version():
    """Regenerated by tools/release.py; a stale bundle would hide the card."""
    notes = release_notes.for_version()
    assert notes["body"], \
        "perun/release_notes.json is stale: run the release script to regenerate it"
